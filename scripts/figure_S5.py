"""
figure_S5.py — Inter-replicate absorbance scatter, both analytes, RAW
channels, 2x2 panel, ACS double-column.

Each acquisition set (led_set1/led_set2/led_set3) plotted as a distinct
marker/colour so
the per-set scatter behind the mean +/- SD summaries in Tables S2 and S4 is
visible directly, for each analyte's primary channel and its crosstalk-
corrected ratio channel:
  (a) Ferricyanide, raw B channel
  (b) Ferricyanide, B/G ratio channel (BdivG)
  (c) Methylene blue, raw R channel
  (d) Methylene blue, R/G ratio channel (RdivG, computed as in figure_S4.py)

Run with: python scripts/figure_S5.py (from the project root).

Outputs -> Data/paper_figures/figure_S5/
    figure_S5_panel.{png,svg,tiff}                composite 2x2 panel
    figure_S5a.{png,svg,tiff} ... figure_S5d.{...} individual panels
    figure_S5_data.csv                             all plotted points
"""

from __future__ import annotations

import sys
from pathlib import Path

import matplotlib
import numpy as np
import pandas as pd

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
from PIL import Image  # noqa: E402

sys.path.insert(0, str(Path(__file__).resolve().parent))
import figstyle as fs  # noqa: E402

# ─── Paths ────────────────────────────────────────────────────────────────────
SCRIPT_DIR = Path(__file__).resolve().parent
PROJ_ROOT = SCRIPT_DIR.parent
DATA_ROOT = PROJ_ROOT / "Data"
FERIC_ABS = DATA_ROOT / "analysis" / "ferricyanide" / "beer_lambert" / "absorbance_table.csv"
MB_ABS = DATA_ROOT / "analysis" / "methylene_blue" / "beer_lambert" / "absorbance_table.csv"
OUT_DIR = DATA_ROOT / "paper_figures" / "figure_S5"
OUT_DIR.mkdir(parents=True, exist_ok=True)

MARKERS = list(fs.SET_MARKERS)
COLORS = list(fs.SET_COLORS)
SET_LABELS = ["Set 1", "Set 2", "Set 3"]

PANEL_W, PANEL_H = 7.0, 6.0
INDIV_W, INDIV_H = 3.33, 2.85
DPI = 600

plt.rcParams.update(
    {
        "font.family": "sans-serif",
        "font.sans-serif": ["Arial", "Helvetica", "DejaVu Sans"],
        "font.size": 7,
        "axes.labelsize": 8,
        "legend.fontsize": 6,
        "xtick.labelsize": 7,
        "ytick.labelsize": 7,
        "axes.linewidth": 0.6,
        "figure.dpi": 150,
    }
)


def bdivg_per_image(df: pd.DataFrame) -> pd.DataFrame:
    """Compute per-image A_B/G from raw/blank means (matches beer_lambert.py's
    BdivG definition, reproduced here so both channels come from one place)."""
    raw = df.pivot_table(
        index=["filename", "set", "concentration_um"], columns="channel", values="raw_mean"
    )
    blank = df.pivot_table(
        index=["filename", "set", "concentration_um"], columns="channel", values="blank_mean"
    )
    g_s = (raw["G1"] + raw["G2"]) / 2
    g_b = (blank["G1"] + blank["G2"]) / 2
    a = -np.log10((raw["B"] / g_s) / (blank["B"] / g_b))
    return a.reset_index(name="absorbance")


def rdivg_per_image(df: pd.DataFrame) -> pd.DataFrame:
    """Compute per-image A_R/G, matching figure_S4.py's RdivG definition."""
    raw = df.pivot_table(
        index=["filename", "set", "concentration_um"], columns="channel", values="raw_mean"
    )
    blank = df.pivot_table(
        index=["filename", "set", "concentration_um"], columns="channel", values="blank_mean"
    )
    g_s = (raw["G1"] + raw["G2"]) / 2
    g_b = (blank["G1"] + blank["G2"]) / 2
    a = -np.log10((raw["R"] / g_s) / (blank["R"] / g_b))
    return a.reset_index(name="absorbance")


def acquisition_sets(sub: pd.DataFrame, letter: str) -> list[str]:
    """Return the three LED acquisition set labels, in order.

    The set label follows the source folder name, which changed from
    Set1/2/3 to led_set1/2/3 when these tables were regenerated by
    s02_calibrate; match on the trailing digit so either spelling works.
    This is the same rule figure_S13.py uses.
    """
    sets = sorted(s for s in sub["set"].unique() if str(s).rstrip()[-1] in "123")
    if len(sets) != 3:
        sys.exit(f"figure_S5: panel ({letter}) expected 3 acquisition sets, found {sets}")
    return sets


def draw_scatter(ax: plt.Axes, sub: pd.DataFrame, title: str, ylabel: str, letter: str) -> None:
    n_drawn = 0
    for si, set_name in enumerate(acquisition_sets(sub, letter)):
        s = sub[sub["set"] == set_name]
        if s.empty:
            continue
        ax.scatter(
            s["concentration_um"],
            s["absorbance"],
            marker=MARKERS[si],
            s=18,
            facecolor="none",
            edgecolor=COLORS[si],
            linewidth=0.9,
            label=SET_LABELS[si],
            zorder=3,
        )
        n_drawn += len(s)
    if n_drawn == 0:
        sys.exit(f"figure_S5: panel ({letter}) has no points to plot")
    print(
        f"    panel ({letter}): {n_drawn} points, "
        f"[c] {sub['concentration_um'].min():g}-"
        f"{sub['concentration_um'].max():g} µM"
    )
    ax.set_xscale("log")
    ax.set_xlabel("[c] (µM)")
    ax.set_ylabel(ylabel)
    ax.spines["top"].set_visible(False)
    ax.spines["right"].set_visible(False)
    ax.axhline(0, color=fs.GRAY, lw=0.5, zorder=1)
    ax.legend(framealpha=0, fontsize=7, loc="upper left", handlelength=1.2)
    ax.set_title(title, fontsize=8, pad=3)
    ax.text(
        0.97,
        0.03,
        f"({letter})",
        transform=ax.transAxes,
        fontsize=8,
        fontweight="bold",
        va="bottom",
        ha="right",
    )


def _save_fig(fig: plt.Figure, stem: str) -> None:
    """Save fig as PNG, SVG and TIFF (TIFF via PIL to avoid a large-canvas bug
    in matplotlib's native TIFF writer with bbox_inches='tight')."""
    png_path = OUT_DIR / f"{stem}.png"
    for ext, path in (("png", png_path), ("svg", OUT_DIR / f"{stem}.svg")):
        fig.savefig(path, dpi=DPI, bbox_inches="tight", format=ext)
    img = Image.open(png_path)
    img.save(OUT_DIR / f"{stem}.tiff", dpi=(DPI, DPI), compression="tiff_lzw")
    print(f"    -> {stem}.png / .svg / .tiff")


def main() -> None:
    print(f"[figure_S5] Output -> {OUT_DIR}\n")

    feric_df = pd.read_csv(FERIC_ABS)
    mb_df = pd.read_csv(MB_ABS)

    panels = [
        (
            "a",
            "Ferricyanide — raw B channel",
            feric_df[feric_df.channel == "B"][
                ["filename", "set", "concentration_um", "absorbance"]
            ],
            "A_B (AU)",
        ),
        ("b", "Ferricyanide — B/G ratio channel", bdivg_per_image(feric_df), "A_B/G (AU)"),
        (
            "c",
            "Methylene blue — raw R channel",
            mb_df[mb_df.channel == "R"][["filename", "set", "concentration_um", "absorbance"]],
            "A_R (AU)",
        ),
        ("d", "Methylene blue — R/G ratio channel", rdivg_per_image(mb_df), "A_R/G (AU)"),
    ]

    print("Building composite panel ...")
    fig, axes = plt.subplots(
        2, 2, figsize=(PANEL_W, PANEL_H), gridspec_kw={"hspace": 0.5, "wspace": 0.5}
    )
    axes_flat = axes.flatten()
    for ax, (letter, title, sub, ylabel) in zip(axes_flat, panels):
        draw_scatter(ax, sub, title, ylabel, letter)
    _save_fig(fig, "figure_S5_panel")
    plt.close(fig)

    print("\nSaving individual panels ...")
    all_rows = []
    for letter, title, sub, ylabel in panels:
        fig_i, ax_i = plt.subplots(figsize=(INDIV_W, INDIV_H))
        draw_scatter(ax_i, sub, title, ylabel, letter)
        fig_i.tight_layout(pad=0.5)
        _save_fig(fig_i, f"figure_S5{letter}")
        plt.close(fig_i)

        sub = sub.copy()
        sub["panel"] = letter
        sub["title"] = title
        all_rows.append(sub)

    print("\nWriting data CSV ...")
    df_all = pd.concat(all_rows, ignore_index=True)
    csv_path = OUT_DIR / "figure_S5_data.csv"
    df_all.to_csv(csv_path, index=False, float_format="%.6f")
    print(f"    -> figure_S5_data.csv  ({len(df_all.columns)} columns, {len(df_all)} rows)")

    print(f"\n[figure_S5] Done.\n  {OUT_DIR}")


if __name__ == "__main__":
    main()
